#!/usr/bin/env python3
"""Generate the checked-in companion display shader with DXC; normal builds need no shader compiler."""
import argparse
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile


def main():
    root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dxc', required=True, type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = root / 'shaders/Companion.hlsl'
    output = root / 'shaders/generated/CompanionSpirv.h'
    arrays = []
    with tempfile.TemporaryDirectory(prefix='simxr-companion-shaders-') as temporary:
        for target in ['unorm', 'srgb']:
            binary = Path(temporary) / f'{target}.spv'
            flags = ['-spirv', '-fspv-target-env=vulkan1.1', '-T', 'ps_6_0', '-E', 'main', '-O3', '-Ges', '-WX']
            if target == 'srgb':
                flags += ['-D', 'SIMXR_SRGB_TARGET']
            subprocess.run([str(args.dxc), *flags, str(source), '-Fo', str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack(f'<{len(data) // 4}I', data)
            if words[0] != 0x07230203:
                raise RuntimeError('DXC did not produce SPIR-V')
            rows = [', '.join(f'0x{word:08x}u' for word in words[i:i + 8])
                    for i in range(0, len(words), 8)]
            arrays.append(f'inline constexpr std::array<std::uint32_t, {len(words)}> {target} = {{\n\t' +
                          ',\n\t'.join(rows) + '\n};')
    digest = hashlib.sha256(source.read_text().encode('utf-8')).hexdigest()
    header = ('// Generated by scripts/generate-companion-shaders.py; do not edit.\n' +
              f'// Companion.hlsl (LF) SHA256: {digest}\n#pragma once\n#include <array>\n#include <cstdint>\n\n' +
              'namespace simxr::app::shader\n{\n' + '\n'.join(arrays) + '\n}\n')
    if args.check:
        if not output.exists() or output.read_text() != header:
            raise SystemExit('Companion shader header differs; regenerate it')
    else:
        output.write_text(header)


if __name__ == '__main__':
    main()
